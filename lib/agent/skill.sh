## Common procedures

### Bootstrap an environment
```bash
bytebabe init
```

### Docker example: clean up and inspect
```bash
bytebabe docker containers   # menu
bytebabe docker clean
bytebabe docker stats
```

### HTTP requests with flux
```bash
bytebabe flux get  https://api.github.com/zen
bytebabe flux post http://localhost:8000/items '{"name":"x"}' \
  --header 'Content-Type: application/json'
```
Non-interactive commands cover source, persistence and rendering; the request
history lives at `$HOME/bytebabe/flux/request_history.json` and needs `jq`.

### Azure DevOps PR flow
```bash
bytebabe az setup <organization> [project]   # short name or full URL
bytebabe az prs                              # requires az auth session
bytebabe az branches <repo>
```
If `az` CLI or its extension is missing, every command prints the exact
install/setup step instead of leaking raw stderr.

### GitHub tools
```bash
bytebabe gh clone <repo>
bytebabe gh prs
bytebabe gh issues
```

## Safety and behavior contracts

- Destructive operations (removal, prune, quarantine) ask for explicit
  confirmation first — keep them that way when scripting.
- Privileged operations use `sudo` only when required.
- Errors include the likely cause and the next step; do not suppress them.
- The `lib/utils/get_docker.sh` upstream installer runs intentionally when
  `bytebabe devtools docker` is invoked.
- Source-safety: loading any `lib/` module has no side effects and commands
  never `exit` from reusable functions; they `return` status codes.

## Keeping this pack fresh

Regenerate with:
```bash
bytebabe agent update
