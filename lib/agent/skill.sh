# ByteBabe CLI — Agent Knowledge Pack

ByteBabe is a single binary entrypoint (`bytebabe`, alias `bb`) with themed
output. All commands run locally with `bash`; interactive menus open when no
arguments are given, and direct mode is available for most modules.

## When to use

- Bootstrap a complete dev environment (`init`)
- Create projects (frontend, backend/Spring) or scaffold files inside them
- Setup and run web servers, databases and API-toolchains
- Manage Docker (containers, images, volumes, compose) without scripting
- Send HTTP requests / run a local JSON server from the terminal (flux)
- Query Azure DevOps PR/branches/projects and GitHub pull requests/issues
- System upkeep: cleanup, backup, firewall, network, stats, sysinfo (prime)

